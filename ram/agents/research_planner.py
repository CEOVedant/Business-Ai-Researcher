def create_research_plan(question):

    return f"""
Research Question:
{question}

Research Plan:

1. Identify the main business objective.
2. Identify the companies or competitors involved.
3. Collect reliable information about each company.
4. Compare products, pricing, market position, and strengths.
5. Verify important claims using multiple sources.
6. Identify conflicting information.
7. Separate facts from assumptions and unknown information.
8. Prepare an executive decision brief.
"""
